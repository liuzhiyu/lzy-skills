# 四象限维度：钩子 × 案例。引擎用此函数对每个视频分桶。
CASE = re.compile(r"这家|有个|一家|老板|店|工厂|案例|县城|男子")
def quad_bucket(r):
    h = bool(r["hook"])
    c = bool(CASE.search(r["title"] or ""))
    if h and c: return "钩子+案例"
    if h: return "只有钩子"
    if c: return "只有案例"
    return "都没有"
